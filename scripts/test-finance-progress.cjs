const assert=require('node:assert/strict');
require('./test-operations.cjs');
const {personalEntry}=require('../lib/finance.ts');
const {defaultCatalog,emptyProgress,validProgress}=require('../lib/progress.ts');
const {viewForPath,PASSWORD_RESET_URL}=require('../lib/routes.ts');
const entry={id:'credit',personId:'p',typologyId:'a',cents:500,description:'Saldo',date:'2026-11-01',batchId:null};
const data={version:1,materials:[],loans:[],movements:[{id:'m',description:'Caixa',category:'Outra',type:'income',amount:10,date:'2026-11-01'}],treasury:{people:[{id:'p',name:'Pessoa',active:true}],types:[{id:'t',name:'Individual'}],typologies:[{id:'a',typeId:'t',name:'Disponível',priority:1,spendable:true}],entries:[entry]}};
const next=personalEntry(data,{...entry,id:'expense',cents:-200});
assert.equal(next.treasury.entries.reduce((s,e)=>s+e.cents,0),300);
assert.deepEqual(next.movements,data.movements);
assert.equal(data.treasury.entries.length,1);
assert.throws(()=>personalEntry(data,{...entry,cents:-501}));
assert.throws(()=>personalEntry(data,{...entry,personId:'other'}));
assert.equal(defaultCatalog.length,42);
assert.deepEqual(['F','A','C','E','I','S'].map(a=>defaultCatalog.filter(g=>g.area===a).length),[6,6,8,8,7,7]);
const p={...emptyProgress,records:[{personId:'p',goalId:'F1',status:'proposed',stage:'caminho',notes:'Preparar atividade',pending:[{id:'task',title:'Caminhada',dueDate:'2026-11-12',done:false}]}]};
assert.ok(validProgress(p,['p']));
assert.equal(validProgress(p,[]),false);
assert.equal(validProgress({...p,records:[{...p.records[0],goalId:'unknown'}]},['p']),false);
assert.equal(validProgress({...p,records:[{...p.records[0],pending:[...p.records[0].pending,...p.records[0].pending]}]},['p']),false);
assert.equal(viewForPath('/financas/individual/p'),'finance');
assert.equal(viewForPath('/progresso/p'),'progress');
assert.equal(viewForPath('/material/tenda'),'materials');
assert.equal(PASSWORD_RESET_URL,'https://cla71.vercel.app/recuperar-password');
console.log('Separação financeira, progresso e endereços: OK');
